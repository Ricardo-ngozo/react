// Helper functions
export function getClubsByLeague(leagueId) {
  return CLUBS.filter(c => c.leagueId === leagueId);
}

export function getClubsByCountry(countryId) {
  return CLUBS.filter(c => c.countryId === countryId);
}

export function getLeaguesByCountry(countryId) {
  return LEAGUES.filter(l => l.countryId === countryId);
}

export function getClubById(id) {
  return CLUBS.find(c => c.id === id);
}

export function getLeagueById(id) {
  return LEAGUES.find(l => l.id === id);
}

export function getCountryById(id) {
  return COUNTRIES.find(c => c.id === id);
}

export function searchClubs(query) {
  const q = query.toLowerCase();
  return CLUBS.filter(c =>
    c.name.toLowerCase().includes(q) ||
    c.shortName.toLowerCase().includes(q) ||
    c.location.toLowerCase().includes(q)
  );
}
